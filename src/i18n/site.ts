type SiteKey = keyof (typeof site)['en'];

/** Translator for the extended strings, falling back to English per key. */
export function useSite(lang: Lang) {
  return (key: SiteKey): string => {
    const table = site[lang] as Record<string, string> | undefined;
    return table?.[key] ?? (site.en as Record<string, string>)[key];
  };
}
